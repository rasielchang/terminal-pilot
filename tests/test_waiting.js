"use strict";
const assert = require("node:assert/strict");
const {browser} = require("./test_navigation.js");
const app = browser();
app.run(`connected = true; selected = 'a';
  sessions = [{id:'a', tool:'codex', binding:'tty:a', phase:'waiting', noticeReason:'permission',
    approvalReviewer:'user', waitingTool:'Bash', lifecycleReady:true, unread:true}];
  var requests = []; api = (...args) => { requests.push(args); throw new Error('Unexpected request'); };
  renderAttention(current());`);
assert.equal(app.node("attention-banner").hidden, false);
assert.equal(app.node("attention-more").open, true);
assert.match(app.node("attention-title").textContent, /Allow/);
assert.match(app.node("attention-detail").textContent, /Bash/);
app.run("sessions[0].unread = false; renderAttention(current())");
assert.equal(app.node("attention-banner").hidden, false, "Reading a notice does not resolve its approval");
app.node("attention-more").open = false;
app.run("renderAttention(current())");
assert.equal(app.node("attention-more").open, false, "Polling must not reopen collapsed details");
app.run("sessions[0].phase = 'running'; renderAttention(current())");
assert.equal(app.node("attention-banner").hidden, true);
app.run("sessions[0].phase = 'waiting'; sessions[0].approvalReviewer = ''; renderAttention(current())");
assert.doesNotMatch(app.node("attention-title").textContent, /按 Allow/);
app.run("sessions[0].approvalReviewer = 'auto_review'; renderAttention(current())");
assert.match(app.node("attention-title").textContent, /審查/);
app.run("sessions[0].noticeReason = 'user_input'; renderAttention(current())");
assert.match(app.node("attention-title").textContent, /回答選項/);
app.run("sessions[0].waitingTool = '<img src=x onerror=alert(1)>'; renderAttention(current())");
assert.match(app.node("attention-detail").textContent, /<img/); // Plain text, never inserted as HTML.
app.run("sessions[0].phase = 'complete'; sessions[0].lifecycleReady = false; renderAttention(current())");
assert.equal(app.node("attention-banner").hidden, false);
assert.match(app.node("attention-title").textContent, /尚未接通/);
assert.equal(app.node("attention-more").open, false);
app.run("sessions[0].lifecycleReady = true; renderAttention(current())");
assert.equal(app.node("attention-banner").hidden, true);
app.run("connected = false; renderAttention(current())");
assert.equal(app.node("attention-read").disabled, true);
app.run("renderAttention({tool:'terminal'});");
assert.equal(app.node("attention-banner").hidden, true);
assert.equal(app.run("requests.length"), 0, "Rendering must not approve, acknowledge or read the Terminal automatically");
console.log("Waiting UI checks passed: visible approval/question state, read-versus-resolved distinction, unknown reviewers, missing hooks, polling and no implicit actions.");
app.run("sessions[0].phase='complete';sessions[0].lifecycleReady=true;sessions[0].codexSocket='/private/managed.sock';sessions[0].codexThreadID='exact';sessions[0].runtime={state:'unavailable'};renderAttention(current())");
assert.match(app.node('attention-title').textContent,/連線尚未恢復/,'Trusted hooks must not hide a disconnected approval channel');
app.run("sessions[0].runtime={state:'idle',canApprove:true};renderAttention(current())");
assert.equal(app.node('attention-banner').hidden,true);
