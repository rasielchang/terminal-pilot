'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const {browser, state, flush} = require('./test_assistant');

// Actual viewport geometry, including browser clamping at the end of a short reply.
const scroll = {scrollHeight:12000, clientHeight:600};
let top = 0;
Object.defineProperty(scroll, 'scrollTop', {get:()=>top, set:value=>{top=Math.max(0,Math.min(value,11400));}});
const context = vm.createContext({window:{},document:{scrollingElement:scroll}});
vm.runInContext(fs.readFileSync('web/reading.js','utf8'),context);
const reading=context.window.PilotReading;
const message=(id,y,target=true)=>({dataset:{messageId:id,readingTarget:String(target)},getBoundingClientRect:()=>({top:y-top})});
reading.start({children:[message('old',100),message('long',8000)]},scroll,112);
assert.equal(top,7888);
reading.start({children:[message('short',11700)]},scroll,112);
assert.equal(top,11400,'Short replies clamp naturally without blank padding');
reading.start({children:[message('reply',8000),message('log',11000,false)]},scroll,112);
assert.equal(top,7888,'A trailing system record must not hide the latest actual reply');
const pane={scrollTop:600,clientTop:1,getBoundingClientRect:()=>({top:100})};
reading.start({children:[{dataset:{},getBoundingClientRect:()=>({top:701})}]},pane);
assert.equal(pane.scrollTop,1188,'Desktop uses its own scroll viewport, not the document');

const reply=(id,text='長回覆')=>({id,text,role:'assistant',kind:'result',created:1});
const respond=async(b,messages)=>{b.calls.at(-1).resolve(state({messages}));await flush();};
(async()=>{
  const b=browser(), a=b.assistant;
  b.scrollingElement.scrollHeight=12000;
  a.update(); await respond(b,[reply(1,'內容\n'.repeat(200))]);
  b.$('brain-messages').children[0].layoutTop=8000; b.frame();
  assert.equal(b.scrollingElement.scrollTop,7988,'Brain opens long results at their beginning');
  assert.ok(b.calls.some(c=>c.path==='/api/brain/ack' && c.data.through===1),'Opening a long result still acknowledges the displayed result');
  b.scrollingElement.scrollTop=11350;
  a.update(); await respond(b,[reply(1,'更長的內容\n'.repeat(300))]); b.frame();
  assert.equal(b.scrollingElement.scrollTop,11350,'Streaming the same reply does not force any scroll');
  b.scrollingElement.scrollTop=11400;
  a.update(); await respond(b,[reply(1),reply(2)]);
  b.$('brain-messages').children.at(-1).layoutTop=11900; b.scrollingElement.scrollHeight=18000; b.frame();
  assert.equal(b.scrollingElement.scrollTop,11888,'A new Brain reply is read from the start');
  b.scrollingElement.scrollTop=500;
  a.update(); await respond(b,[reply(1),reply(2),reply(3)]); b.frame();
  assert.equal(b.scrollingElement.scrollTop,500,'Brain polling never interrupts older reading');
  a.switchTopic('',{latest:true}); await respond(b,[reply(1),reply(2),reply(3)]);
  b.$('brain-messages').children.at(-1).layoutTop=13000;b.frame();
  assert.equal(b.scrollingElement.scrollTop,12988,'A Brain notification overrides a saved position only for its requested topic');
  b.$('brain-latest').click(); b.frame(1); b.scrollingElement.scrollTop=900;b.frame();
  assert.equal(b.scrollingElement.scrollTop,900,'User scrolling cancels a pending jump');
  a.update(); const old=b.calls.at(-1);
  a.chooseMode('manager'); a.chooseMode('assistant');
  assert.notEqual(b.calls.at(-1),old,'Changing mode does not leave the read request locked');
  await respond(b,[reply(1)]); old.resolve(state({messages:[reply(99)]}));await flush();b.frame();
  assert.equal(b.$('brain-messages').children[0].dataset.messageId,'1');
  const hidden=browser();hidden.assistant.update();await respond(hidden,[reply(1)]);
  hidden.context.document.hidden=true;hidden.frame();
  hidden.context.document.hidden=false;hidden.assistant.refresh();hidden.frame();
  assert.equal(hidden.scrollingElement.scrollTop,2988,'A background layout retries when visible');
  const pending=browser(), decision={session:{id:'one',binding:'tty1',title:'網站'},requests:[{id:'consent',state:'pending'}]};
  pending.scrollingElement.scrollHeight=15000;
  pending.$('brain-decisions').layoutTop=12000;
  pending.assistant.update(); pending.calls.at(-1).resolve(state({messages:[reply(1)],decisions:[decision]}));
  await flush(); pending.frame();
  assert.equal(pending.scrollingElement.scrollTop,11988,'Brain opens a waiting conversation at the bottom decision');
  assert.ok(!pending.calls.some(c=>c.path==='/api/brain/ack'),'Showing a decision does not mark unseen results read');
  pending.scrollingElement.scrollTop=400;
  pending.assistant.update(); pending.calls.at(-1).resolve(state({messages:[reply(1)],decisions:[decision]}));
  await flush(); pending.frame();
  assert.equal(pending.scrollingElement.scrollTop,400,'Polling a pending decision never drags older reading');
  pending.$('brain-latest').click(); pending.frame();
  assert.equal(pending.scrollingElement.scrollTop,11988,'Latest remains a shortcut to the pending decision');
  console.log('Reading checks passed: long/short replies, sticky headers, desktop panes, system records, Brain notifications, streaming, read state and navigation races.');
})().catch(error=>{console.error(error);process.exitCode=1;});
