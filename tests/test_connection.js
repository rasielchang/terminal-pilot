"use strict";
const assert=require('node:assert/strict');
const {browser}=require('./test_navigation.js');
(async()=>{
  const app=browser();
  app.node('send').firstChild={textContent:''};
  app.run(`selected='a';token='paired';connected=true;sessions=[{id:'a',binding:'tty:a',tool:'codex',canSend:true}];
    $('message').value='保留的草稿';updateComposer();`);
  assert.equal(app.node('send').disabled,false);
  app.run('connected=false;updateComposer()');
  assert.equal(app.node('send').disabled,true);
  assert.match(app.node('send-hint').textContent,/連線中斷/);
  assert.equal(app.node('reconnect').hidden,false);
  app.run('connected=true;updateComposer()');
  assert.equal(app.node('send').disabled,false);
  assert.equal(app.node('message').value,'保留的草稿');
  app.run(`loadThread=originalLoadThread;api=async()=>{throw new TypeError('Load failed')};`);
  await app.run('loadThread()');
  assert.equal(app.run("feedback.get('a').kind"),'history');
  app.run(`api=async()=>({session:sessions[0],messages:[],source:'none'});`);
  await app.run('loadThread()');
  assert.equal(app.run("feedback.has('a')"),false,'Successful read must clear the previous network error');
  app.run(`feedback.set('a',{text:'送出結果未知',error:true});`);
  await app.run('loadThread()');
  assert.equal(app.run("feedback.get('a').text"),'送出結果未知','Reading must not erase ambiguous delivery warnings');
  app.run(`sessions[0].canSend=false;sessions[0].phase='waiting';updateComposer()`);
  assert.match(app.node('send-hint').textContent,/核准/);
  assert.equal(app.node('send').disabled,true);
  console.log('Connection recovery checks passed: retained draft, clear stale load errors, preserve delivery warnings and explicit send-disabled reasons.');
})().catch(error=>{console.error(error);process.exitCode=1});
