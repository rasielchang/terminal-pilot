"use strict";
const assert = require('node:assert/strict');
const {browser} = require('./test_navigation.js');

(async () => {
  const app = browser();
  app.node('send').firstChild = {textContent:''};
  app.run(`token='paired';connected=true;selected='shell';
    sessions=[{id:'shell',binding:'tty:exact',tool:'terminal',canSend:true,title:'Shell'}];
    renderAttention=()=>{};renderProgress=()=>{};poll=()=>{};
    var calls=[],sequence=0,terminalText='$ pwd\\n/project\\n<script>literal</script>';
    requestID=()=>String(++sequence);
    api=async(path,data)=>{calls.push({path,data});return path.startsWith('/api/thread')?
      {session:sessions[0],source:'terminal',messages:[],terminalText}:{sent:true};};
    $('workspace').classList.add('detail');$('message').value='pwd';originalRenderHeader();`);
  assert.equal(app.node('compose').hidden,false);
  assert.equal(app.node('send').disabled,false);
  assert.equal(app.node('terminal-enter').hidden,false);
  assert.equal(app.node('terminal-enter').disabled,false);
  assert.match(app.node('message').placeholder,/Terminal/);
  await app.node('compose').handlers.submit({preventDefault(){}});
  assert.equal(app.run('calls[0].path'),'/api/terminal/input');
  assert.equal(app.run('calls[0].data.text'),'pwd');
  assert.equal(app.run('calls[0].data.binding'),'tty:exact');
  app.node('message').value='keep draft';
  await app.node('terminal-enter').handlers.click();
  assert.equal(app.run('calls[1].data.text'),'');
  assert.equal(app.node('message').value,'keep draft');
  await app.run('originalLoadThread()'); app.frame();
  assert.equal(app.node('messages').children[0].tagName,'PRE');
  assert.match(app.node('messages').children[0].textContent,/<script>literal<\/script>/);
  assert.equal(app.node('messages').children[0].children.length,0,'Terminal output is literal text');
  assert.equal(app.node('history-note').hidden,true);
  assert.equal(app.document.scrollingElement.scrollTop,3000);
  app.document.scrollingElement.scrollTop=200;
  app.run("terminalText+='\\nmore output'");
  await app.run('originalLoadThread()');app.frame();
  assert.equal(app.document.scrollingElement.scrollTop,200,'New output must not pull someone away from older lines');
  const late=app.run('var finish;api=()=>new Promise(resolve=>finish=resolve);originalLoadThread()');
  app.run(`selected='other';selectionGeneration++;finish({session:sessions[0],source:'terminal',messages:[],terminalText:'WRONG SCREEN'});`);
  await late;
  assert.doesNotMatch(app.node('messages').children[0].textContent,/WRONG SCREEN/);
  app.run(`selected='shell';connected=false;originalRenderHeader();`);
  assert.equal(app.node('terminal-enter').disabled,true);
  assert.equal(app.node('send').disabled,true);
  app.run(`sessions[0].tool='codex';originalRenderHeader();`);
  assert.equal(app.node('terminal-enter').hidden,true,'Agent UI must not expose raw terminal input');
  console.log('Plain Terminal UI checks passed: compose, Enter, literal output, whole-page reading position, offline and stale target.');
})().catch(error=>{console.error(error);process.exitCode=1;});
