'use strict';
const assert=require('node:assert/strict');
const {browser,state,flush}=require('./test_assistant');
(async()=>{
  const b=browser({today:true}), a=b.assistant, today=b.context.window.PilotToday;
  const unified=()=>state({unified:true,topics:[],topic:{id:''},backend:{thread:'brain-thread'},pending:[],activities:[],cursor:0,messages:[]});
  const row=id=>({id:`projects/demo/work-items/${id}.json`,title:`同專案 ${id}`});
  a.update();b.calls.at(-1).resolve(unified());await flush();b.frame();
  b.$('brain-input').value='保留草稿，另外也要談另一件事';b.$('brain-input').handlers.input();
  b.scrollingElement.scrollTop=712;
  today.options.discuss(row('a'));b.frame();
  assert.equal(a.page(),'chat');assert.equal(a.topic(),'');
  assert.match(b.$('brain-reference-label').textContent,/a.json/);
  assert.equal(b.$('brain-input').value,'保留草稿，另外也要談另一件事');
  assert.ok(!b.calls.some(c=>c.path==='/api/brain/message'||c.path==='/api/brain/work'||c.path==='/api/send'));
  a.choosePage('today');assert.equal(b.scrollingElement.scrollTop,712);
  today.options.discuss(row('b'));
  assert.match(b.$('brain-reference-label').textContent,/b.json/);
  b.$('brain-reference-clear').click();assert.equal(b.$('brain-reference').hidden,true);
  assert.equal(b.$('brain-input').value,'保留草稿，另外也要談另一件事');
  a.choosePage('today');today.options.discuss(row('a'));
  b.$('brain-compose').handlers.submit({preventDefault(){}});
  const first=b.calls.at(-1);
  assert.equal(first.path,'/api/brain/message');assert.equal(first.data.referenceCard,row('a').id);
  assert.equal(first.data.text,b.$('brain-input').value);
  assert.equal(first.data.topic,undefined);assert.equal(first.data.source,undefined);
  first.reject(new TypeError('offline'));await flush();
  a.choosePage('today');assert.equal(today.options.discussionDisabled,true);
  today.options.discuss(row('b'));b.$('brain-reference-clear').click();
  assert.match(b.$('brain-reference-label').textContent,/a.json/,'Uncertain retry cannot silently change reference');
  a.choosePage('chat');b.$('brain-compose').handlers.submit({preventDefault(){}});
  const retry=b.calls.at(-1);assert.deepEqual(retry.data,first.data);
  retry.resolve({accepted:true});await flush();
  b.calls.at(-1).resolve(unified());await flush();
  assert.equal(b.$('brain-reference').hidden,true);
  assert.deepEqual(b.opened,[]);
  a.choosePage('today');assert.equal(b.scrollingElement.scrollTop,712);
  console.log('Card discussion: A/B/cancel, draft, panel position, immutable retry, same Brain endpoint, no worker actions passed.');
})().catch(e=>{console.error(e);process.exitCode=1;});
