"use strict";
const assert = require("node:assert/strict");
const {browser} = require("./test_navigation.js");
const app = browser();
app.run(`connected = true; selected = 'a'; sessions = [{id:'a', tool:'codex', phase:'complete', status:'回覆完成', updatedAt:1}];
  progressMessages.set('a', {role:'assistant', phase:'commentary', text:'我還在處理 <img src=x>', time:new Date().toISOString()});
  renderProgress(current());`);
assert.match(app.node("progress-title").textContent, /尚未收到完成/);

assert.equal(app.node("progress-panel").hidden, false);
app.run("sessions[0].runtime = {state:'running'}; renderProgress(current())");
assert.equal(app.node("progress-title").textContent, "處理中");
app.run("sessions[0].phase = 'waiting'; sessions[0].approvalReviewer = 'user'; renderProgress(current())");
assert.match(app.node("progress-title").textContent, /Allow/);
assert.doesNotMatch(app.node("progress-panel").className, /working/);
app.run("connected = false; renderProgress(current())");
assert.match(app.node("progress-title").textContent, /連線中斷/);
app.run("connected = true; renderProgress({id:'b', tool:'codex', phase:'running'})");
assert.equal(app.run("progressState({id:'b',tool:'codex'}).preview"), "", "Never show another session's progress");
app.run("renderProgress({id:'b', tool:'codex', phase:'running', lifecycleReady:false, runtime:{state:'unavailable'}})");
assert.match(app.node("progress-title").textContent, /即時狀態未連接/);
assert.doesNotMatch(app.node("progress-panel").className, /working/);
app.node("progress-latest").handlers.click();
assert.equal(app.document.scrollingElement.scrollTop, app.document.scrollingElement.scrollHeight);
app.run("renderProgress({tool:'terminal'})");
assert.equal(app.node("progress-panel").hidden, true);
console.log("Progress checks passed: commentary, formal running/waiting, disconnection, exact session, safe text and jump to latest.");
app.run(`connected=true; sessions[0].phase='running'; sessions[0].runtime={state:'running'};
  sessions[0].activeTurnStartedAt=Date.now()/1000-492; renderProgress(current());`);
assert.match(app.node('progress-elapsed').textContent, /本輪已經過 8 分 12 秒/);
app.run(`sessions[0].runtime={state:'unavailable'};sessions[0].lifecycleReady=false;
  sessions[0].activeTurnStartedAt=0;progressStarts.set('a',Date.now()/1000-480);renderProgress(current());`);
assert.match(app.node('progress-elapsed').textContent, /距離送出 8 分 0 秒（尚未連上即時狀態）/);
app.run(`sessions[0].phase='complete';sessions[0].runtime={state:'idle'};
  progressMessages.set('a',{role:'assistant',phase:'final_answer',text:'完成',time:new Date().toISOString()});renderProgress(current());`);
assert.equal(app.node('progress-elapsed').hidden,true);
assert.equal(app.node('progress-title').textContent,'回覆完成');
app.run(`sessions[0].runtime={state:'unavailable'};sessions[0].alive=true;sessions[0].lifecycleReady=false;
  sessions[0].turnProgress={state:'active',startedAt:Date.now()/1000-1080};
  progressStarts.set('a',Date.now()/1000-60);renderProgress(current());`);
assert.equal(app.node('progress-title').textContent,'本輪進行中');
assert.match(app.node('progress-elapsed').textContent,/本輪已經過 18 分 0 秒/,'Steering does not reset the turn clock');
